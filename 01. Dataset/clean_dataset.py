"""
Clean the raw synthetic bank extracts and write Clean_*.csv plus a Cleaning Log.

Asset classification is NOT corrected here: wrong classifications are a reporting exception that the SQL checks
(02. SQL Scripts/05) must find and report, as a bank's reporting team would.

Run:  python clean_dataset.py   (after generate_dataset.py)
"""
import os
import shutil
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RAW, OUT = os.path.join(HERE, "Raw Dataset"), os.path.join(HERE, "Cleaned Dataset")
os.makedirs(OUT, exist_ok=True)
log = []

for t in ["ChartOfAccounts", "Deposits", "Branches"]:
    shutil.copy(os.path.join(RAW, t + ".csv"), os.path.join(OUT, f"Clean_{t}.csv"))
log.append(("ChartOfAccounts, Deposits, Branches", "No issues found (copied as is)", 0))

g = pd.read_csv(os.path.join(RAW, "GLBalances.csv"), dtype={"GLCode": str, "Amount": str})
txt = g.Amount.str.contains(",")
g["Amount"] = g.Amount.str.replace(",", "", regex=False).astype(float)
log.append(("GLBalances", "Amounts exported as text with thousand separators converted to numbers", int(txt.sum())))
coa = pd.read_csv(os.path.join(RAW, "ChartOfAccounts.csv"), dtype={"GLCode": str})
orphan = ~g.GLCode.isin(coa.GLCode)
log.append(("GLBalances", "GL codes not in the chart of accounts (checked)", int(orphan.sum())))
g.to_csv(os.path.join(OUT, "Clean_GLBalances.csv"), index=False)

lb = pd.read_csv(os.path.join(RAW, "LoanBook.csv"))
n0 = len(lb)
lb = lb.drop_duplicates()
log.append(("LoanBook", "Duplicate extract rows removed", n0 - len(lb)))
fixed = lb.Segment.str.title().str.replace("Msme", "MSME")
up = lb.Segment != fixed
lb["Segment"] = fixed
log.append(("LoanBook", "Segment names standardised ('HOME LOAN' -> 'Home Loan')", int(up.sum())))
lb["DPDBucket"] = pd.cut(lb.DPD, [-1, 0, 30, 60, 90, 10 ** 6], labels=["0 Current", "1-30 SMA-0", "31-60 SMA-1", "61-90 SMA-2", "90+ NPA"]).astype(str)
log.append(("LoanBook", "Added DPDBucket (days past due band)", len(lb)))
lb.to_csv(os.path.join(OUT, "Clean_LoanBook.csv"), index=False)

finals = {f"Clean_{t}": len(pd.read_csv(os.path.join(OUT, f"Clean_{t}.csv"))) for t in
          ["ChartOfAccounts", "GLBalances", "LoanBook", "Deposits", "Branches"]}
with open(os.path.join(HERE, "Cleaning Log.md"), "w", encoding="utf-8") as fh:
    fh.write("# Data Cleaning Log\n\nGenerated by `clean_dataset.py`. Counts are rows (or values) affected.\n\n")
    fh.write("| Table | Issue / action | Count |\n|---|---|---:|\n")
    for t, a, n in log:
        fh.write(f"| {t} | {a} | {n:,} |\n")
    fh.write("\nAsset-class tags are left as received. Loans tagged Standard while more than 90 days past due are reported as an\n"
             "exception by `02. SQL Scripts/05_Asset_Classification_Exceptions.sql`, not silently fixed.\n")
    fh.write("\n## Final row counts\n\n| Table | Rows |\n|---|---:|\n")
    for k, v in finals.items():
        fh.write(f"| {k} | {v:,} |\n")
print(pd.DataFrame(log, columns=["Table", "Action", "Count"]).to_string(index=False))
